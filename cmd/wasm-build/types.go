package main

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"go/types"
	"maps"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/gzuidhof/tygo/tygo"
)

const leadingParams = 2

var tsReservedWords = strings.Fields("await catch class debugger delete do enum export extends false finally function " +
	"implements in instanceof let new null private protected public static super this throw true try typeof void while with yield")

func generateTypes(root, out string) error {
	wasmTypes, err := typeSpecs(filepath.Join(root, "cmd", "wasm"))
	if err != nil {
		return err
	}
	repositoryTypes, err := typeSpecs(filepath.Join(root, "internal", "storage", "repository"))
	if err != nil {
		return err
	}

	mappings := map[string]string{}
	var goSource, backend strings.Builder
	backend.WriteString("export interface LocalBackend {\n")
	for _, field := range wasmTypes["repositories"].(*ast.StructType).Fields.List {
		repository := field.Type.(*ast.SelectorExpr).Sel.Name
		fmt.Fprintf(&backend, "  %s: {\n", repository)
		for _, method := range repositoryTypes[repository].(*ast.InterfaceType).Methods.List {
			name := method.Names[0].Name
			writeMethod(&goSource, &backend, mappings, repository+name, name, method.Type.(*ast.FuncType))
		}
		backend.WriteString("  };\n")
	}
	backend.WriteString("}\n")

	converted, err := tygo.ConvertGoToTypescript(goSource.String(), tygo.PackageConfig{
		OptionalType:     "null",
		PreserveComments: "none",
		TypeMappings:     mappings,
	})
	if err != nil {
		return err
	}

	imports := strings.Join(slices.Sorted(maps.Values(mappings)), ", ")
	output := fmt.Sprintf("// Code generated by wasm-build. DO NOT EDIT.\nimport type { %s } from \"@/api/models\";\n\n%s\n%s", imports, converted, backend.String())
	if err := os.MkdirAll(filepath.Dir(out), 0o755); err != nil {
		return err
	}
	return os.WriteFile(out, []byte(output), 0o644)
}

func writeMethod(goSource, backend *strings.Builder, mappings map[string]string, typeName, name string, fn *ast.FuncType) {
	fmt.Fprintf(goSource, "type %s struct {\n", typeName)

	var params []string
	index := 0
	for _, field := range fn.Params.List {
		for _, ident := range field.Names {
			if index++; index > leadingParams {
				writeField(goSource, mappings, ident.Name, field.Type)
				params = append(params, fmt.Sprintf("%s: %s[%q]", tsParamName(ident.Name), typeName, ident.Name))
			}
		}
	}

	result := "void"
	if results := fn.Results.List; len(results) == 2 {
		resultType := results[0].Type
		if star, ok := resultType.(*ast.StarExpr); ok {
			resultType = star.X
		}
		writeField(goSource, mappings, "result", resultType)
		result = typeName + `["result"]`
	}

	goSource.WriteString("}\n")
	fmt.Fprintf(backend, "    %s(%s): Promise<%s>;\n", name, strings.Join(params, ", "), result)
}

func writeField(goSource *strings.Builder, mappings map[string]string, key string, expr ast.Expr) {
	ast.Inspect(expr, func(node ast.Node) bool {
		if selector, ok := node.(*ast.SelectorExpr); ok {
			mappings[types.ExprString(selector)] = selector.Sel.Name
		}
		return true
	})

	goType := types.ExprString(expr)
	tag := fmt.Sprintf(`json:"%s"`, key)
	if goType == "[]byte" {
		tag += ` tstype:"Uint8Array<ArrayBuffer>"`
	}
	fmt.Fprintf(goSource, "\tF%s %s `%s`\n", key, goType, tag)
}

func tsParamName(name string) string {
	if slices.Contains(tsReservedWords, name) {
		return name + "_"
	}
	return name
}

func typeSpecs(dir string) (map[string]ast.Expr, error) {
	paths, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		return nil, err
	}

	specs := map[string]ast.Expr{}
	fset := token.NewFileSet()
	for _, path := range paths {
		file, err := parser.ParseFile(fset, path, nil, parser.SkipObjectResolution)
		if err != nil {
			return nil, err
		}
		ast.Inspect(file, func(node ast.Node) bool {
			if spec, ok := node.(*ast.TypeSpec); ok {
				specs[spec.Name.Name] = spec.Type
			}
			return true
		})
	}
	return specs, nil
}
